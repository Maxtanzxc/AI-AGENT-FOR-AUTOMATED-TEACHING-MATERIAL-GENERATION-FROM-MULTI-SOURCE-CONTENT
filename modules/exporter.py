class NumberedCanvas(canvas.Canvas):
    """Two-pass canvas to dynamically compute and draw total page numbers and running headers/footers."""
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_decorations(self, page_count):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#64748B"))

        # Running Header (pages > 1)
        if self._pageNumber > 1:
            self.drawString(1.8 * cm, 29.7 * cm - 1.2 * cm, "EduForge AI • Automated Teaching Material System")
            self.drawRightString(21.0 * cm - 1.8 * cm, 29.7 * cm - 1.2 * cm, datetime.now().strftime("%B %d, %Y"))
            self.setStrokeColor(colors.HexColor("#E2E8F0"))
            self.setLineWidth(0.5)
            self.line(1.8 * cm, 29.7 * cm - 1.35 * cm, 21.0 * cm - 1.8 * cm, 29.7 * cm - 1.35 * cm)

        # Running Footer (all pages)
        self.drawString(1.8 * cm, 1.2 * cm, "Generated by EduForge AI — Autonomous Pedagogical Engine")
        page_str = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(21.0 * cm - 1.8 * cm, 1.2 * cm, page_str)
        self.setStrokeColor(colors.HexColor("#E2E8F0"))
        self.setLineWidth(0.5)
        self.line(1.8 * cm, 1.45 * cm, 21.0 * cm - 1.8 * cm, 1.45 * cm)

        self.restoreState()


def clean_text_for_pdf(text: str) -> str:
    """
    Sanitize and convert markdown text into valid ReportLab XML.
    Fixes character encoding issues, unclosed tags, and dangling markdown asterisks.
    """
    if not text:
        return ""

    # 1. Replace unsupported Unicode characters with standard ASCII equivalents
    replacements = {
        '\u2010': '-', '\u2011': '-', '\u2012': '-', '\u2013': '-', '\u2014': '-', '\u2015': '-', '\u2212': '-',
        '\u2018': "'", '\u2019': "'", '\u201a': "'", '\u201b': "'",
        '\u201c': '"', '\u201d': '"', '\u201e': '"', '\u201f': '"', '\u00ab': '"', '\u00bb': '"',
        '\u2026': '...', '\u00a0': ' ', '\u202f': ' ', '\u2007': ' ', '\u200b': '',
        '\u2022': '&bull;', '\u25cf': '&bull;', '\u25aa': '-',
        '\u2191': '&uarr;', '\u2193': '&darr;', '\u2192': '-&gt;',
        '\u2248': '~', '\u2264': '&le;', '\u2265': '&ge;', '\u00b1': '+/-'
    }
    for char, repl in replacements.items():
        text = text.replace(char, repl)

    # 2. Fix dangling or unpaired asterisks
    if text.count('**') % 2 != 0:
        text = re.sub(r'^\*\*\s*', '', text)
        text = re.sub(r'\s*\*\*$', '', text)
        if text.count('**') % 2 != 0:
            text = text.replace('**', '')

    if text.count('*') % 2 != 0:
        text = re.sub(r'^\*\s*', '', text)
        text = re.sub(r'\s*\*$', '', text)
        if text.count('*') % 2 != 0:
            text = text.replace('*', '')

    # 3. Escape XML entities
    text = text.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')

    # 4. Convert markdown bold and italic syntax to ReportLab HTML tags
    text = re.sub(r'\*\*(.+?)\*\*', r'<b>\1</b>', text)
    text = re.sub(r'__(.+?)__', r'<b>\1</b>', text)
    text = re.sub(r'(?<![<b>])\*(.+?)\*(?![</b>])', r'<i>\1</i>', text)
    text = re.sub(r'(?<![<b>])_(.+?)_(?![</b>])', r'<i>\1</i>', text)

    text = text.replace('&lt;b&gt;', '<b>').replace('&lt;/b&gt;', '</b>')
    text = text.replace('&lt;i&gt;', '<i>').replace('&lt;/i&gt;', '</i>')
    text = text.replace('&lt;bull&gt;', '&bull;')

    return text.strip()


def _is_speaker_note_line(line: str) -> bool:
    """True for a speaker-note line however it's wrapped."""
    if not line:
        return False
    stripped = re.sub(r'^[\-\*\u2022\s]+', '', line).strip()
    stripped = re.sub(r'^\*\*(.*?)\*\*', r'\1', stripped).strip()
    stripped = re.sub(r'^_(.*?)_', r'\1', stripped).strip()
    return bool(re.match(r'^speaker\s*note\s*:', stripped, re.IGNORECASE))


