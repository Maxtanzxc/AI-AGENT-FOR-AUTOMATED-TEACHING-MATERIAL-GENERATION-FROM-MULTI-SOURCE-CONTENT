def add_text_cards_slide(prs, title: str, content_lines: list, topic: str, slide_num: int, total_slides: int, level: str):
    """
    Render a text-only slide as badge cards. Layout varies with point count instead
    of always defaulting to the same grid:
      - 1 point:  one large card
      - 2 points: side-by-side pair (uses the widescreen canvas instead of stacking)
      - 3 points: stacked wide cards
      - 4-5 points: 2-column grid
    Capped at 5 points so body text never has to shrink past legibility.
    """
    blank_layout = prs.slide_layouts[6]
    slide = prs.slides.add_slide(blank_layout)
    add_slide_chrome(slide, topic, title, slide_num, total_slides, level)

    lines = [l for l in content_lines if l.strip()]
    if not lines:
        lines = ["Key concepts and discussion for this slide."]

    n = len(lines)
    top_start = 1.62
    bottom_edge = 6.85
    avail_h = bottom_edge - top_start

    if n == 1:
        card_h = min(2.7, avail_h)
        c_top = top_start + (avail_h - card_h) / 2
        head, body = _parse_card_content(lines[0])
        _add_content_card(slide, 0.9, c_top, 11.533, card_h, 1, head, body, tier="hero")

    elif n == 2:
        col_w = 5.6
        gap = 0.333
        card_h = min(2.9, avail_h)
        c_top = top_start + (avail_h - card_h) / 2
        for i, line_text in enumerate(lines):
            c_left = 0.9 + i * (col_w + gap)
            head, body = _parse_card_content(line_text)
            _add_content_card(slide, c_left, c_top, col_w, card_h, i + 1, head, body, tier="normal")

    elif n == 3:
        card_h = 1.6
        gap = 0.22
        group_h = card_h * 3 + gap * 2
        top0 = top_start + max(0, (avail_h - group_h) / 2)
        for i, line_text in enumerate(lines):
            c_top = top0 + i * (card_h + gap)
            head, body = _parse_card_content(line_text)
            _add_content_card(slide, 0.9, c_top, 11.533, card_h, i + 1, head, body, tier="normal")

    else:
        display_lines = lines[:5]
        num_rows = (len(display_lines) + 1) // 2
        card_h = (avail_h - (num_rows - 1) * 0.22) / num_rows
        col1_left = 0.9
        col2_left = 6.833
        col_w = 5.6

        for i, line_text in enumerate(display_lines):
            col = i % 2
            row = i // 2
            c_left = col1_left if col == 0 else col2_left
            c_top = top_start + row * (card_h + 0.22)
            head, body = _parse_card_content(line_text)
            _add_content_card(slide, c_left, c_top, col_w, card_h, i + 1, head, body, tier="compact")


def extract_table_from_slide_lines(lines: list):
    """
    Detects if slide lines contain a Markdown table.
    Returns (intro_lines, table_data) where table_data is:
      {'headers': [...], 'rows': [[...], ...]}
    or (lines, None) if no table is present.
    """
    if not lines:
        return lines, None

    table_rows = []
    intro_lines = []

    for l in lines:
        s = l.strip()
        if not s:
            continue
        # Check if line looks like a markdown table row: starts with '|' and has inner '|'
        if s.startswith("|") and "|" in s[1:]:
            cells = [c.strip() for c in s.strip("|").split("|")]
            # Check if separator row like |:---|:---|
            is_separator = all(re.match(r'^[\s\-:]+$', c) for c in cells if c)
            if is_separator:
                continue
            # Clean markdown bold/italics
            cleaned_cells = [re.sub(r'[\*#_]', '', c).strip() for c in cells]
            if any(cleaned_cells):
                table_rows.append(cleaned_cells)
        else:
            intro_lines.append(s)

    # Must have at least 2 rows (1 header + at least 1 data row)
    if len(table_rows) >= 2:
        headers = table_rows[0]
        data_rows = table_rows[1:]
        # Normalize row length to match headers length
        norm_rows = []
        for r in data_rows:
            if len(r) < len(headers):
                r = r + [""] * (len(headers) - len(r))
            elif len(r) > len(headers):
                r = r[:len(headers)]
            norm_rows.append(r)
        return intro_lines, {"headers": headers, "rows": norm_rows}

    return lines, None


def add_table_slide(prs, title: str, intro_lines: list, table_data: dict, topic: str, slide_num: int, total_slides: int, level: str):
    """
    Renders a dedicated, widescreen 16:9 table slide for comparison or structured curriculum data.
    Keeps the whole table unified in one sleek, elevated container rather than
    fragmenting rows into disconnected cards.
    """
    blank_layout = prs.slide_layouts[6]
    slide = prs.slides.add_slide(blank_layout)
    add_slide_chrome(slide, topic, title, slide_num, total_slides, level)

    headers = table_data.get("headers", [])
    data_rows = table_data.get("rows", [])
    if not headers or not data_rows:
        return

    left = 0.9
    avail_w = 11.533
    top_start = 1.60
    avail_h = 5.25

    # If there is an introductory line, render it above the table
    if intro_lines:
        clean_intro = sanitize_text_for_export(" ".join(intro_lines[:2]))
        ibox = slide.shapes.add_textbox(Inches(left), Inches(top_start), Inches(avail_w), Inches(0.40))
        itf = ibox.text_frame
        itf.word_wrap = True
        itf.margin_left = 0
        itf.margin_right = 0
        itf.margin_top = 0
        itf.margin_bottom = 0
        ip = itf.paragraphs[0]
        ir = ip.add_run()
        ir.text = clean_intro
        ir.font.size = Pt(13)
        ir.font.color.rgb = COLOR_TEXT_MUTED
        ir.font.bold = False
        table_top = top_start + 0.45
        table_h = min(avail_h - 0.45, 4.70)
    else:
        table_top = top_start + 0.10
        table_h = min(avail_h - 0.10, 5.05)

    R = len(data_rows) + 1
    C = len(headers)

    # Elevation shadow behind table
    _add_shadow_rect(slide, left, table_top, avail_w, table_h, radius_shape=False)

    t_shape = slide.shapes.add_table(R, C, Inches(left), Inches(table_top), Inches(avail_w), Inches(table_h))
    tbl = t_shape.table

    # Proportionate column widths
    if C == 2:
        tbl.columns[0].width = Inches(3.5)
        tbl.columns[1].width = Inches(avail_w - 3.5)
    elif C == 3:
        tbl.columns[0].width = Inches(2.7)
        tbl.columns[1].width = Inches((avail_w - 2.7) / 2)
        tbl.columns[2].width = Inches((avail_w - 2.7) / 2)
    else:
        w1 = min(2.4, avail_w / C)
        rem = (avail_w - w1) / (C - 1)
        tbl.columns[0].width = Inches(w1)
        for c in range(1, C):
            tbl.columns[c].width = Inches(rem)

    font_size_body = Pt(10.5) if R > 6 else Pt(11.5)

    all_matrix = [headers] + data_rows
    for r_idx, row in enumerate(all_matrix):
        for c_idx, val in enumerate(row):
            cell = tbl.cell(r_idx, c_idx)
            cell.vertical_anchor = MSO_ANCHOR.MIDDLE
            cell.margin_left = Inches(0.16)
            cell.margin_right = Inches(0.16)
            cell.margin_top = Inches(0.08)
            cell.margin_bottom = Inches(0.08)
            cell.fill.solid()

            if r_idx == 0:
                cell.fill.fore_color.rgb = COLOR_DARK_BG
                f_color = COLOR_BRAND_CYAN
                is_b = True
                f_size = Pt(12.5)
            else:
                if r_idx % 2 == 1:
                    cell.fill.fore_color.rgb = COLOR_CARD_BG
                else:
                    cell.fill.fore_color.rgb = RGBColor(241, 245, 249)
                f_color = COLOR_TEXT_MAIN
                is_b = (c_idx == 0)
                f_size = font_size_body

            tf = cell.text_frame
            tf.word_wrap = True
            p = tf.paragraphs[0]
            p.alignment = PP_ALIGN.LEFT
            run = p.add_run()
            run.text = sanitize_text_for_export(val)
            run.font.bold = is_b
            run.font.size = f_size
            run.font.color.rgb = f_color


def add_illustrated_slide(prs, title: str, content_lines: list, image_bytes: bytes, topic: str, slide_num: int, total_slides: int, level: str):
    """
    60/40 split: badge cards on the left, a framed visual on the right. Capped at
    4 points so cards stay readable next to the image column.
    """
    blank_layout = prs.slide_layouts[6]
    slide = prs.slides.add_slide(blank_layout)
    add_slide_chrome(slide, topic, title, slide_num, total_slides, level)

    lines = [l for l in content_lines if l.strip()]
    if not lines:
        lines = ["Core pedagogical discussion for this topic."]

    display_lines = lines[:4]
    num_cards = len(display_lines)

    total_avail_h = 5.15
    gap = 0.2
    card_w = 7.2
    top_start = 1.60

    # Fixed, tiered heights so 1-2 points read as spacious rather than stretched;
    # only the dense 4-point case fills the full column (it has enough content to).
    tier_height = {1: 3.0, 2: 2.3, 3: 1.55, 4: (total_avail_h - 3 * gap) / 4}
    tier_name = {1: "hero", 2: "normal", 3: "normal", 4: "compact"}
    card_h = tier_height[num_cards]

    for i, line_text in enumerate(display_lines):
        c_top = top_start + i * (card_h + gap)
        head, body = _parse_card_content(line_text)
        _add_content_card(slide, 0.9, c_top, card_w, card_h, i + 1, head, body, tier=tier_name[num_cards])

    img_card_left = 8.4
    img_card_w = 4.033
    img_card_h = 5.15

    _add_shadow_rect(slide, img_card_left, top_start, img_card_w, img_card_h)
    img_frame = slide.shapes.add_shape(MSO_SHAPE.ROUNDED_RECTANGLE, Inches(img_card_left), Inches(top_start), Inches(img_card_w), Inches(img_card_h))
    img_frame.fill.solid()
    img_frame.fill.fore_color.rgb = COLOR_CARD_BG
    _no_line(img_frame)
    img_frame.shadow.inherit = False

    if image_bytes:
        try:
            pil_img = Image.open(BytesIO(image_bytes))
            orig_w, orig_h = pil_img.size
            aspect = orig_w / max(orig_h, 1)

            max_w = 3.6
            max_h = 4.0

            if aspect > (max_w / max_h):
                fit_w = max_w
                fit_h = max_w / aspect
            else:
                fit_h = max_h
                fit_w = max_h * aspect

            pic_left = img_card_left + (img_card_w - fit_w) / 2.0
            pic_top = top_start + 0.35 + (max_h - fit_h) / 2.0

            img_stream = BytesIO(image_bytes)
            slide.shapes.add_picture(img_stream, Inches(pic_left), Inches(pic_top), Inches(fit_w), Inches(fit_h))

            cap_box = slide.shapes.add_textbox(Inches(img_card_left + 0.2), Inches(top_start + img_card_h - 0.46), Inches(img_card_w - 0.4), Inches(0.4))
            ctf = cap_box.text_frame
            ctf.word_wrap = True
            cp = ctf.paragraphs[0]
            cp.alignment = PP_ALIGN.CENTER
            cr = cp.add_run()
            cr.text = "Visual Concept Diagram · EduForge AI"
            cr.font.size = Pt(9)
            cr.font.color.rgb = COLOR_TEXT_MUTED

        except Exception as e:
            print(f"Error rendering slide image in PPTX: {e}")


def export_to_pptx(content: str, topic: str, slide_images: list = None, level: str = "Secondary") -> str:
    """
    Export lecture slides content to a modern 16:9 widescreen PowerPoint presentation:
    dark cover -> light content slides (badge cards, layout varied by point count) ->
    dark closing slide, with no accent stripes anywhere in the chrome.

    A leading 'Subtitle: ...' line, however it's wrapped, is extracted before
    slide parsing and used to drive the cover slide's subtitle instead of
    falling through into slide 1's card content.
    """
    os.makedirs("outputs", exist_ok=True)
    filename = f"outputs/{topic.replace(' ', '_')}_slides.pptx"

    cover_subtitle, content = extract_cover_subtitle(content)

    prs = Presentation()
    prs.slide_width = Inches(SLIDE_W)
    prs.slide_height = Inches(SLIDE_H)

    parsed_slides = parse_slides_from_content(content)
    if not parsed_slides:
        parsed_slides = [(topic or "Lecture Slides", ["No slide content available."])]

    total_content_slides = len(parsed_slides)

    add_cover_slide(prs, topic, level, total_content_slides, subtitle=cover_subtitle)

    for idx, (title, lines) in enumerate(parsed_slides):
        slide_num = idx + 1
        img_bytes = None
        if slide_images and idx < len(slide_images):
            img_bytes = slide_images[idx]

        intro_lines, table_data = extract_table_from_slide_lines(lines)

        if table_data and len(table_data["rows"]) >= 1:
            add_table_slide(prs, title, intro_lines, table_data, topic, slide_num, total_content_slides, level)
        elif img_bytes:
            add_illustrated_slide(prs, title, lines, img_bytes, topic, slide_num, total_content_slides, level)
        else:
            add_text_cards_slide(prs, title, lines, topic, slide_num, total_content_slides, level)

    add_closing_slide(prs, topic, total_content_slides)

    prs.save(filename)
    return filename


