def _render_mcq_pdf_flowables(content: str, styles) -> list:
    """Parse MCQ quiz structure and render as elegant question cards with green answer callouts."""
    flowables = []
    lines = content.split("\n")

    q_blocks = []
    current_block = []
    header_lines = []
    in_questions = False

    for line in lines:
        line_clean = line.strip()
        line_no_bullet = re.sub(r'^[\-\*\u2022\s]+', '', line_clean).strip()

        if re.match(r'^(?:\*\*)?Q\s*\d+[\.:]', line_no_bullet, re.IGNORECASE):
            in_questions = True
            if current_block:
                q_blocks.append(current_block)
            current_block = [line_no_bullet]
        elif in_questions:
            current_block.append(line_clean)
        else:
            if line_clean and line_clean not in ("---", "***", "___"):
                header_lines.append(line_clean)

    if current_block:
        q_blocks.append(current_block)

    # Render intro headers before Q1 (omit redundant topic title repeats)
    for h in header_lines:
        h_clean = re.sub(r'^[\-\*\u2022\s]+', '', h).strip()
        h_clean = re.sub(r'\*+$', '', h_clean).strip()
        if h_clean:
            flowables.append(Paragraph(clean_text_for_pdf(h_clean), styles["DocMeta"]))

    if header_lines:
        flowables.append(Spacer(1, 0.25 * cm))

    for block in q_blocks:
        q_header = ""
        q_prompt = []
        options = []
        answer = ""
        explanation = ""

        mode = "header"
        for raw_line in block:
            if not raw_line:
                continue

            clean_line = re.sub(r'^[\-\*\u2022\s]+', '', raw_line).strip()
            clean_line = re.sub(r'\*+$', '', clean_line).strip()

            if re.match(r'^(?:\*\*)?Q\s*\d+[\.:]', clean_line, re.IGNORECASE):
                q_header = clean_text_for_pdf(clean_line)
                mode = "prompt"
            elif re.match(r'^(?:\*\*)?[A-Da-d]\)', clean_line):
                opt_formatted = re.sub(r'^\**([A-Da-d]\))\**\s*', r'<b>\1</b> ', clean_line)
                options.append(clean_text_for_pdf(opt_formatted))
                mode = "options"
            elif re.search(r'^(?:\*\*)?Answer\s*[:\*\-]', clean_line, re.IGNORECASE):
                ans_text = re.sub(r'^(?:\*\*)?Answer\s*[:\*\-]+\s*', '', clean_line, flags=re.IGNORECASE).strip(' *')
                answer = clean_text_for_pdf(ans_text)
                mode = "answer"
            elif re.search(r'^(?:\*\*)?Explanation\s*[:\*\-]', clean_line, re.IGNORECASE):
                exp_text = re.sub(r'^(?:\*\*)?Explanation\s*[:\*\-]+\s*', '', clean_line, flags=re.IGNORECASE).strip(' *')
                explanation = clean_text_for_pdf(exp_text)
                mode = "explanation"
            else:
                if mode == "prompt":
                    q_prompt.append(clean_text_for_pdf(clean_line))
                elif mode == "explanation":
                    explanation += " " + clean_text_for_pdf(clean_line)
                elif mode == "options":
                    if options:
                        options[-1] += " " + clean_text_for_pdf(clean_line)

        card = []
        full_q = q_header
        if q_prompt:
            full_q += f"<br/>{' '.join(q_prompt)}"
        card.append(Paragraph(full_q, styles["QuestionTitle"]))
        card.append(Spacer(1, 0.15 * cm))

        for opt in options:
            card.append(Paragraph(opt, styles["Option"]))
        card.append(Spacer(1, 0.2 * cm))

        if answer or explanation:
            box_rows = []
            if answer:
                box_rows.append([Paragraph(f"<b>✔ Correct Answer:</b> {answer}", styles["AnswerTitle"])])
            if explanation:
                box_rows.append([Paragraph(f"<b>Explanation:</b> {explanation}", styles["ExplanationText"])])

            ans_table = Table(box_rows, colWidths=[17.4 * cm])
            ans_table.setStyle(TableStyle([
                ('BACKGROUND', (0,0), (-1,-1), colors.HexColor("#F0FDF4")),
                ('BOX', (0,0), (-1,-1), 0.5, colors.HexColor("#BBF7D0")),
                ('LINEBEFORE', (0,0), (0,-1), 3.0, colors.HexColor("#22C55E")),
                ('TOPPADDING', (0,0), (-1,-1), 5),
                ('BOTTOMPADDING', (0,0), (-1,-1), 5),
                ('LEFTPADDING', (0,0), (-1,-1), 10),
                ('RIGHTPADDING', (0,0), (-1,-1), 10),
            ]))
            card.append(ans_table)

        card.append(Spacer(1, 0.45 * cm))
        flowables.append(KeepTogether(card))

    return flowables


def export_to_pdf(content: str, topic: str, output_type: str) -> str:
    """Export generated content to a polished, professional PDF with custom typography, cards, and tables."""
    os.makedirs("outputs", exist_ok=True)
    safe_topic = re.sub(r'[\/:*?"<>| ]', '_', topic)
    safe_type = re.sub(r'[\/:*?"<>| ]', '_', output_type)
    filename = f"outputs/{safe_topic}_{safe_type}.pdf"

    doc = SimpleDocTemplate(
        filename,
        pagesize=A4,
        rightMargin=1.8 * cm,
        leftMargin=1.8 * cm,
        topMargin=1.8 * cm,
        bottomMargin=1.8 * cm
    )

    styles = _get_pdf_styles()
    story = []

    # Hero Header Banner
    story.append(Paragraph(output_type.upper(), styles["DocBadge"]))
    story.append(Paragraph(clean_text_for_pdf(topic), styles["DocTitle"]))
    meta_text = f"EduForge AI • Generated Teaching Material • {datetime.now().strftime('%B %d, %Y')}"
    story.append(Paragraph(meta_text, styles["DocMeta"]))
    story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#CBD5E1"), spaceBefore=4, spaceAfter=12))

    # Determine if content is MCQ format
    is_mcq = (output_type == "MCQ Questions") or bool(
        re.search(r'(?:^|\n)\s*(?:[\-\*\u2022\s]*)(?:\*\*)?Q\s*\d+[\.:]', content, re.IGNORECASE)
    )

    if is_mcq:
        mcq_flowables = _render_mcq_pdf_flowables(content, styles)
        story.extend(mcq_flowables)
    else:
        # General parser with markdown table, headings, bullets, and slide support
        lines = content.split("\n")
        i = 0
        while i < len(lines):
            line = lines[i]
            line_strip = line.strip()

            if not line_strip or line_strip in ("---", "***", "___"):
                story.append(Spacer(1, 0.15 * cm))
                i += 1
                continue

            if _is_speaker_note_line(line_strip):
                i += 1
                continue

            # Markdown Table detection
            if line_strip.startswith("|") and line_strip.count("|") >= 2:
                table_lines = []
                while i < len(lines) and lines[i].strip().startswith("|"):
                    table_lines.append(lines[i].strip())
                    i += 1

                rows = []
                for tline in table_lines:
                    cells = [c.strip() for c in tline.strip('|').split('|')]
                    if all(set(c).issubset({'-', ':', ' '}) for c in cells if c):
                        continue
                    if not rows:
                        row = [Paragraph(clean_text_for_pdf(c), styles["TableHeader"]) for c in cells]
                    else:
                        row = [Paragraph(clean_text_for_pdf(c), styles["TableCell"]) for c in cells]
                    rows.append(row)

                if rows:
                    num_cols = len(rows[0])
                    col_width = (17.4 * cm) / num_cols
                    table = Table(rows, colWidths=[col_width] * num_cols)
                    table.setStyle(TableStyle([
                        ('BACKGROUND', (0,0), (-1,0), colors.HexColor("#1E293B")),
                        ('GRID', (0,0), (-1,-1), 0.5, colors.HexColor("#CBD5E1")),
                        ('TOPPADDING', (0,0), (-1,-1), 5),
                        ('BOTTOMPADDING', (0,0), (-1,-1), 5),
                        ('LEFTPADDING', (0,0), (-1,-1), 6),
                        ('RIGHTPADDING', (0,0), (-1,-1), 6),
                        *[('BACKGROUND', (0, r), (-1, r), colors.HexColor("#F8FAFC")) for r in range(1, len(rows), 2)]
                    ]))
                    story.append(table)
                    story.append(Spacer(1, 0.25 * cm))
                continue

            # Slide Header
            if re.match(r'^(?:#+\s*)?SLIDE\s*\d+', line_strip, re.IGNORECASE):
                clean_slide = re.sub(r'[\*#_\[\]]', '', line_strip).strip()
                story.append(Paragraph(clean_text_for_pdf(clean_slide), styles["SlideHeader"]))
                story.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor("#E2E8F0"), spaceBefore=2, spaceAfter=6))
                i += 1
                continue

            # Headings
            if line_strip.startswith("## "):
                h_text = line_strip[3:].strip()
                story.append(Paragraph(clean_text_for_pdf(h_text), styles["H2"]))
                i += 1
                continue
            elif line_strip.startswith("### "):
                h_text = line_strip[4:].strip()
                story.append(Paragraph(clean_text_for_pdf(h_text), styles["H3"]))
                i += 1
                continue

            # Bullets: line starts with - or • or + or * (single star + space)
            is_bullet = bool(re.match(r'^[\-\u2022\+]\s+', line_strip) or re.match(r'^\*(?!\*)\s+', line_strip))
            if is_bullet:
                bullet_body = re.sub(r'^[\-\u2022\+\*]\s*', '', line_strip).strip()
                story.append(Paragraph(f"&bull; {clean_text_for_pdf(bullet_body)}", styles["Bullet"]))
                i += 1
                continue

            # Normal text / Bold text
            story.append(Paragraph(clean_text_for_pdf(line_strip), styles["Body"]))
            i += 1

    doc.build(story, canvasmaker=NumberedCanvas)
    return filename


def sanitize_text_for_export(text: str) -> str:
    """Normalize unicode spaces, dashes, math symbols, and unsupported characters for clean document generation."""
    if not text:
        return ""
    replacements = {
        '\u2010': '-', '\u2011': '-', '\u2012': '-', '\u2013': '-', '\u2014': '-', '\u2015': '-', '\u2212': '-',
        '\u2018': "'", '\u2019': "'", '\u201a': "'", '\u201b': "'",
        '\u201c': '"', '\u201d': '"', '\u201e': '"', '\u201f': '"', '\u00ab': '"', '\u00bb': '"',
        '\u2026': '...', '\u00a0': ' ', '\u202f': ' ', '\u2007': ' ', '\u200b': '', '\u2022': '-', '\u25cf': '-', '\u25aa': '-',
        '\u2248': '~', '\u2264': '<=', '\u2265': '>=', '\u00b1': '+/-', '\u2192': '->',
        '\u2080': '0', '\u2081': '1', '\u2082': '2', '\u2083': '3', '\u2084': '4',
        '\u2085': '5', '\u2086': '6', '\u2087': '7', '\u2088': '8', '\u2089': '9',
        '\u2070': '0', '\u00b9': '1', '\u00b2': '2', '\u00b3': '3', '\u2074': '4'
    }
    for char, repl in replacements.items():
        text = text.replace(char, repl)
    return text


def extract_cover_subtitle(content: str) -> tuple:
    """
    Pull a 'Subtitle: ...' line (plain, bulleted, or bolded) out of the deck's
    front matter — before slide 1's body content — so it can drive the cover
    slide instead of falling through into the card parser as an ordinary bullet
    and showing up as card 01.

    Only scans the handful of lines around the top of the content / before the
    first SLIDE header, so a line elsewhere in the deck that happens to start
    with 'Subtitle:' is left alone.

    Returns (subtitle_text_or_None, content_with_that_line_removed).
    """
    if not content:
        return None, content

    lines = content.split("\n")
    subtitle_pattern = re.compile(r'^[\-\*\s]*\**\s*subtitle\s*[:\-\u2013]\s*(.+?)\**\s*$', re.IGNORECASE)

    first_header_idx = None
    for i, line in enumerate(lines):
        if re.search(r'(?:^|[\*#_\[\(]\s*)SLIDE\s*\d+\b', line.strip(), re.IGNORECASE):
            first_header_idx = i
            break

    search_end = (first_header_idx + 6) if first_header_idx is not None else min(len(lines), 6)

    for i in range(0, min(search_end, len(lines))):
        m = subtitle_pattern.match(lines[i].strip())
        if m:
            subtitle_text = sanitize_text_for_export(re.sub(r'\*\*(.+?)\*\*', r'\1', m.group(1)).strip())
            remaining = lines[:i] + lines[i + 1:]
            return subtitle_text, "\n".join(remaining)

    return None, content


def parse_slides_from_content(content: str) -> list:
    """
    Robustly parse slide titles and content lines from markdown text.
    Handles any header variation: '**SLIDE 1 – TITLE**', '## SLIDE 1: Title', 'SLIDE 1:', etc.
    Preserves inline formatting (such as bold concept keywords) while removing bullet prefixes.
    """
    clean_content = sanitize_text_for_export(content)
    slides = []
    current_title = ""
    current_lines = []

    for line in clean_content.split("\n"):
        line_strip = line.strip()
        if not line_strip or line_strip in ("---", "***", "___", "==="):
            continue

        is_slide_header = bool(
            re.search(r'(?:^|[\*#_\[\(]\s*)SLIDE\s*\d+\b', line_strip, re.IGNORECASE)
        )

        if is_slide_header:
            if current_title or current_lines:
                slides.append((current_title or "Slide", current_lines))
            clean_title = re.sub(r'[\*#_\[\]\(\)]', '', line_strip).strip()
            clean_title = re.sub(r'^#+\s*', '', clean_title).strip()
            current_title = clean_title
            current_lines = []
        else:
            if line_strip.startswith("```") or _is_speaker_note_line(line_strip):
                continue

            if re.match(r'^[\|\s\-:]+$', line_strip) and '-' in line_strip:
                continue

            clean_text = line_strip
            if clean_text.startswith(("- ", "• ", "* ")):
                clean_text = clean_text[2:].strip()
            elif clean_text.startswith(("-", "•")):
                clean_text = clean_text[1:].strip()

            cl = clean_text.lower().strip()
            if cl.endswith(":") and (len(cl.split()) <= 4 or cl.startswith(("by the end of", "students will be able to"))):
                continue

            if clean_text and clean_text not in ("---", "***"):
                current_lines.append(clean_text)

    if current_title or current_lines:
        slides.append((current_title or "Slide", current_lines))

    if not slides:
        sections = re.split(r'\n(?=##\s+)', clean_content)
        for sec in sections:
            sec_lines = [l.strip() for l in sec.split("\n") if l.strip() and l.strip() not in ("---", "***")]
            if sec_lines:
                title = re.sub(r'^#+\s*', '', sec_lines[0]).strip()
                title = re.sub(r'[\*#_\[\]]', '', title).strip()
                lines = [re.sub(r'^[-\*•\s]+', '', l).strip() for l in sec_lines[1:] if l.strip()]
                slides.append((title or "Slide", lines))

    return slides


