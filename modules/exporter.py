def _add_content_card(slide, left: float, top: float, width: float, height: float, badge_num: int, heading: str, body: str, is_compact: bool = False, tier: str = "normal"):
    """
    Render one card: a soft flat shadow, a white rounded surface, a small colored
    number badge in the top-left corner, a bold heading beside it, and the
    description below. This trio (shadow + card + circle badge) is the one motif
    repeated on every slide instead of a border or accent line.

    `tier` scales the badge and type to the card's actual height so a slide with
    one or two points reads as deliberately spacious rather than as a stretched,
    half-empty card: "hero" (>=2.4in tall), "normal" (~1.6-2.4in), "compact" (dense grids).

    Body (and heading) text is measured against its box with `_fit_font_size`
    before being drawn, so a longer line automatically renders smaller instead
    of spilling past the bottom edge of the card.
    """
    _add_shadow_rect(slide, left, top, width, height)

    card = slide.shapes.add_shape(MSO_SHAPE.ROUNDED_RECTANGLE, Inches(left), Inches(top), Inches(width), Inches(height))
    card.fill.solid()
    card.fill.fore_color.rgb = COLOR_CARD_BG
    _no_line(card)
    card.shadow.inherit = False

    pad = 0.28 if tier == "hero" else 0.24
    circle_d = {"hero": 0.5, "normal": 0.42, "compact": 0.36}[tier]
    badge_color = COLOR_BRAND_CYAN if badge_num % 2 == 1 else COLOR_BRAND_TEAL
    circle_left = left + pad
    circle_top = top + pad
    _add_badge_circle(slide, circle_left, circle_top, circle_d, f"{badge_num:02d}", badge_color)

    heading_font_max = {"hero": 19, "normal": 14.5, "compact": 13.5}[tier]
    body_font_max = {"hero": 16, "normal": 13, "compact": 12.5}[tier]
    heading_font_min = 11.0
    body_font_min = 9.5

    if heading:
        head_left = circle_left + circle_d + 0.18
        head_width = max((left + width) - pad - head_left, 0.5)
        head_height = circle_d + 0.1
        head_box = slide.shapes.add_textbox(Inches(head_left), Inches(circle_top - 0.03), Inches(head_width), Inches(head_height))
        htf = head_box.text_frame
        htf.word_wrap = True
        htf.vertical_anchor = MSO_ANCHOR.MIDDLE
        htf.margin_left = 0
        htf.margin_right = 0
        htf.margin_top = 0
        htf.margin_bottom = 0
        hp = htf.paragraphs[0]
        hp.alignment = PP_ALIGN.LEFT
        hr = hp.add_run()
        hr.text = heading
        hr.font.bold = True
        hr.font.size = Pt(_fit_font_size(heading, head_width, head_height, heading_font_max, min_pt=heading_font_min))
        hr.font.color.rgb = COLOR_TEXT_MAIN
        body_top = top + pad + circle_d + 0.14
    else:
        body_top = top + pad + circle_d + 0.10

    if body:
        body_left = left + pad
        body_width = width - 2 * pad
        body_height = max((top + height) - body_top - pad, 0.3)
        body_box = slide.shapes.add_textbox(Inches(body_left), Inches(body_top), Inches(body_width), Inches(body_height))
        btf = body_box.text_frame
        btf.word_wrap = True
        btf.margin_left = 0
        btf.margin_right = 0
        btf.margin_top = 0
        btf.margin_bottom = 0
        clean_body = re.sub(r'\*\*(.+?)\*\*', r'\1', body).strip()
        bp = btf.paragraphs[0]
        bp.alignment = PP_ALIGN.LEFT
        bp.line_spacing = 1.18
        br = bp.add_run()
        br.text = clean_body
        br.font.size = Pt(_fit_font_size(clean_body, body_width, body_height, body_font_max,
                                          min_pt=body_font_min, line_spacing=1.18))
        br.font.color.rgb = COLOR_TEXT_MAIN


